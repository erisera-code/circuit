// Generates the Storybook stories from the family gallery's component list.
//
//   stories/designs/<design>.stories.js   ONE canonical markup per component (the
//                                        design-engine snippet), rendered under
//                                        that design — the same markup in every
//                                        file, which is the whole point.
//   stories/compare.stories.js           the canonical markup under every design,
//                                        side by side, per component.
//   stories/sources/<system>.stories.js  the sibling systems' OWN stylesheets on
//                                        their own markup, for reference only.
//
// Run after changing examples/family/components.mjs.
import { mkdir, writeFile } from "node:fs/promises";
import { COMPONENTS, SYSTEMS } from "../examples/family/components.mjs";
import { INSTANCES } from "../stories/_shared.js";

const exportName = (id) => id.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const OUT = new URL("../stories/", import.meta.url).pathname;
await mkdir(`${OUT}designs`, { recursive: true });
await mkdir(`${OUT}sources`, { recursive: true });

for (const design of INSTANCES) {
  const lines = [
    `// GENERATED by scripts/gen-stories.mjs — do not edit.`,
    `import { frame } from "../_shared.js";`,
    `export default { title: "Designs/${design}", parameters: { docs: { description: { component: "The canonical classless markup of every component, rendered under the \\"${design}\\" design. Every Designs/* section uses byte-identical markup — only the design changes." } } } };`,
  ];
  for (const c of COMPONENTS) {
    lines.push(`export const ${exportName(c.id)} = { name: "${c.n}. ${c.title}", render: (_, { globals }) => frame("design-engine", "${c.id}", { ...globals, instance: "${design}" }), parameters: { docs: { description: { story: ${JSON.stringify(c.note || "")} } } } };`);
  }
  await writeFile(`${OUT}designs/${design}.stories.js`, lines.join("\n") + "\n");
}

const cmp = [
  `// GENERATED by scripts/gen-stories.mjs — do not edit.`,
  `import { compareDesigns } from "./_shared.js";`,
  `export default { title: "Compare", parameters: { docs: { description: { component: "One component, one markup, every design. The design-engine snippet for the component is rendered under all thirteen designs; use the toolbar to switch the colour scheme." } } } };`,
];
for (const c of COMPONENTS) cmp.push(`export const ${exportName(c.id)} = { name: "${c.n}. ${c.title}", render: (_, { globals }) => compareDesigns("${c.id}", globals) };`);
await writeFile(`${OUT}compare.stories.js`, cmp.join("\n") + "\n");

for (const s of SYSTEMS.filter((s) => s.id !== "design-engine")) {
  const lines = [
    `// GENERATED by scripts/gen-stories.mjs — do not edit.`,
    `import { frame } from "../_shared.js";`,
    `export default { title: "Source stylesheets/${s.title}", parameters: { docs: { description: { component: "${s.title}'s OWN stylesheet on its OWN markup (${s.repo}) — reference for the ${s.id} design, not the shared markup." } } } };`,
  ];
  for (const c of COMPONENTS) lines.push(`export const ${exportName(c.id)} = { name: "${c.n}. ${c.title}", render: (_, { globals }) => frame("${s.id}", "${c.id}", globals) };`);
  await writeFile(`${OUT}sources/${s.id}.stories.js`, lines.join("\n") + "\n");
}
console.log(`✓ generated ${INSTANCES.length} design files, 1 compare file, ${SYSTEMS.length - 1} source files (${COMPONENTS.length} stories each)`);
